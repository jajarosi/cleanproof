export function fmt(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** Traduit un message d'erreur Postgres/Supabase en message lisible. */
export function errorMessage(dict: Dict, raw: string | undefined | null) {
  if (!raw) return dict.errors.generic;
  for (const key of Object.keys(dict.errors) as (keyof Dict["errors"])[]) {
    if (raw.includes(key)) return dict.errors[key];
  }
  if (raw.includes("duplicate key")) return dict.errors.duplicate_name;
  return dict.errors.generic;
}
